/*Primitive Data Types (single value)

 Number → numeric values
 Example: 10, 99.5

 String → text (inside "" or '')
 Example: "Aiyan"

 Boolean → true / false
 Example: true

 Null → intentional empty value
 Example: null

 Undefined → variable declared but no value
 Example: let x;

 BigInt → very large numbers
 Example: 12345678901234567890n

 Symbol → unique value (advanced)
 Example: Symbol("id")

 ==============================

 🔹 Non-Primitive (Reference) Data Types

 Object → key-value pair
 Example: { name: "Aiyan", age: 21 }

 Array → list of values
 Example: [1, 2, 3, 4]

 Function → block of code
 Example: function greet() {}
*/
